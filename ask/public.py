"""Curated public Q&A for Ask Your Listening (XX-08).

Logged-out visitors never trigger a model call. They see a fixed set
of questions (public_questions.json) answered over the fixture marts,
not real listening data, matching the public Patterns tab. The
answers live in public_cache.json, which the owner regenerates with
`scripts/refresh_ask_cache.py` (live model, so it costs a few calls)
and commits. The public tab only appears once the cache exists.
"""

import datetime as dt
import json
import logging
from collections.abc import Callable
from pathlib import Path
from typing import Any

import ask

log = logging.getLogger(__name__)

HERE = Path(__file__).resolve().parent
QUESTIONS_PATH = HERE / "public_questions.json"
CACHE_PATH = HERE / "public_cache.json"
DATA_SOURCE = "fixture marts (tests/evals/fixture_marts.sql)"


def load_questions(path: Path = QUESTIONS_PATH) -> list[str]:
    return json.loads(path.read_text())["questions"]


def load_cache(path: Path | None = None) -> list[dict[str, Any]] | None:
    """Cached answers, or None if the cache hasn't been generated."""
    path = path if path is not None else CACHE_PATH
    if not path.exists():
        log.info("ask public cache: %s missing", path)
        return None
    return json.loads(path.read_text())["entries"]


def refresh_cache(
    questions: list[str],
    *,
    client: Any,
    connect: Callable[[], Any],
    model: str,
    path: Path | None = None,
) -> list[dict[str, Any]]:
    """Answer every question and write the cache.

    All or nothing: a guard rejection or unusable reply raises and
    nothing is written, so a curated question that the model can't
    answer safely gets reworded rather than silently dropped.
    """
    path = path if path is not None else CACHE_PATH
    entries = [
        ask.result_dict(
            ask.ask(q, client=client, connect=connect, model=model)
        )
        for q in questions
    ]
    data = {
        "about": "Generated by scripts/refresh_ask_cache.py; do not "
        "edit by hand.",
        "model": model,
        "generated_at": dt.datetime.now(dt.UTC).isoformat(
            timespec="seconds"
        ),
        "data": DATA_SOURCE,
        "entries": entries,
    }
    path.write_text(json.dumps(data, indent=2) + "\n")
    log.info("ask public cache: wrote %d entries to %s", len(entries), path)
    return entries
